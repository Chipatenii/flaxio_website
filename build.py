"""Build the Flaxio website into static pages for cPanel hosting.

Edit template.html (layout + content) and services.json (service
detail pages), then run:

    python build.py

It writes index.html, about.html, services.html, one .html file per service
(ppe.html, sulphuric-acid.html ...), sectors.html, contact.html,
cookie-policy.html, 404.html and sitemap.xml into this folder.
Upload those files plus assets/, .htaccess and robots.txt to public_html.
"""
import html
import json
import re
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BASE_URL = 'https://flaxioinvestment.com'
SITE = 'Flaxio Investment Limited'

TEMPLATE = (ROOT / 'template.html').read_text(encoding='utf-8')
SERVICES = json.loads((ROOT / 'services.json').read_text(encoding='utf-8'))

PAGES = [
    # (url path, template section, active nav item, title, description)
    ('/', 'home', 'home',
     f'{SITE} | Mining and Industrial Supply in Kitwe, Zambia',
     'Flaxio Investment Limited is a Zambian-owned supplier of sulphuric acid, mining chemicals, '
     'mining and electrical equipment, PPE, industrial valves and flanges, laboratory chemicals, '
     'construction materials, general hardware, fire extinguishers and hazardous waste management, '
     'based in Kitwe, Copperbelt.'),
    ('/about.html', 'about', 'about',
     f'About Us | {SITE}',
     'Learn about Flaxio Investment Limited, a Zambian-owned industrial supplier in Kitwe built on '
     'integrity, safety and operational excellence. Our mission, vision, values and registration details.'),
    ('/services.html', 'services', 'services',
     f'Our Services | {SITE}',
     'Eleven supply and service lines for mining and industry in Zambia: sulphuric acid, mining and '
     'laboratory chemicals, hazardous waste management, mining and electrical equipment, PPE, valves, '
     'construction materials, hardware and fire extinguishers.'),
    ('/sectors.html', 'sectors', 'sectors',
     f'Sectors We Serve | {SITE}',
     'Flaxio supplies the mining, manufacturing, construction and commercial sectors in Zambia with '
     'chemicals, equipment and environmental solutions.'),
    ('/contact.html', 'contact', 'contact',
     f'Contact Us | {SITE}',
     'Request a quote from Flaxio Investment Limited. Visit us at 1018 Blantyre Road, Kitwe, call '
     '+260 979 069 890, WhatsApp us or email info@flaxioinvestment.com.'),
    ('/cookie-policy.html', 'cookies', None,
     f'Cookie Policy | {SITE}',
     'How the Flaxio Investment Limited website uses essential storage, preferences and third-party resources.'),
]
for slug, svc in SERVICES.items():
    PAGES.append((f'/{slug}.html', 'service', 'services',
                  f"{svc['title']} | {SITE}", svc['lead']))

SECTION_RE = re.compile(
    r'(?:<!-- =+\n\s+PAGE: [^\n]*\n\s+=+ -->\n)?'
    r'<section class="page[^"]*" id="page-([\w-]+)">.*?</section>\n', re.S)
SOURCE_NOTE_RE = re.compile(r'<!--\n  FLAXIO INVESTMENT LIMITED corporate website.*?-->\n', re.S)
GENERATED_NOTE = ('<!-- GENERATED by build.py from template.html. '
                  'Do not edit here: edit the source and run  python build.py -->\n')


def esc(text):
    return html.escape(text, quote=True)


def render(section, nav, title, description, url, robots='index, follow', service=None):
    out = SOURCE_NOTE_RE.sub(GENERATED_NOTE, TEMPLATE, count=1)

    def keep(m):
        if m.group(1) != section:
            return ''
        return m.group(0).replace(f'class="page" id="page-{section}"',
                                  f'class="page is-active" id="page-{section}"')
    out = SECTION_RE.sub(keep, out)
    if f'id="page-{section}"' not in out:
        raise SystemExit(f'section page-{section} not found in template')

    if nav:
        out = out.replace(f'data-nav="{nav}">',
                          f'data-nav="{nav}" class="is-current" aria-current="page">')

    values = {
        'TITLE': esc(title), 'DESCRIPTION': esc(description),
        'URL': esc(url), 'ROBOTS': robots,
    }
    if service:
        values.update({
            'SVC_TITLE': esc(service['title']),
            'SVC_LEAD': esc(service['lead']),
            'SVC_IMAGE': esc('/' + service['image'].lstrip('/')),
            'SVC_IMAGE_ALT': esc(service['imageAlt']),
            'SVC_NUMBER': esc(service['number']),
            'SVC_DESCRIPTION': esc(service['description']),
            'SVC_POINTS': ''.join(f'<li>{esc(p)}</li>' for p in service['points']),
            'SVC_TAGS': ''.join(f'<span class="tag">{esc(t)}</span>' for t in service['tags']),
        })
    out = re.sub(r'\{\{([A-Z_]+)\}\}', lambda m: values[m.group(1)], out)
    if '—' in out:
        raise SystemExit(f'em dash found in output for {url}')
    return out


def write(rel, content):
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding='utf-8', newline='\n')
    print('wrote', rel)


def main():
    for url_path, section, nav, title, description in PAGES:
        service = SERVICES[url_path[1:-5]] if section == 'service' else None
        rel = 'index.html' if url_path == '/' else url_path[1:]
        write(rel, render(section, nav, title, description, BASE_URL + url_path, service=service))

    write('404.html', render('404', None, f'Page Not Found | {SITE}',
                             'The page you are looking for could not be found.',
                             BASE_URL + '/', robots='noindex, follow'))

    today = date.today().isoformat()
    urls = ''.join(
        f'  <url>\n    <loc>{BASE_URL}{p}</loc>\n    <lastmod>{today}</lastmod>\n'
        f'    <priority>{"1.0" if p == "/" else "0.8" if p[1:-5] not in SERVICES else "0.6"}</priority>\n  </url>\n'
        for p, *_ in PAGES)
    write('sitemap.xml', '<?xml version="1.0" encoding="UTF-8"?>\n'
          '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + urls + '</urlset>\n')


if __name__ == '__main__':
    main()
